"""
Skill references rendered from the ontology bundle.

Runtime and domain skills carry *procedure*; anything they say about the domain
(which designations are ambiguous, which facet values exist, which caveat a trust
tier requires, how a panel is sequenced) is generated here from the loaded
ontology so a skill can never drift from the knowledge the gate enforces.
Rendered references never contain reference or critical numbers.

A skill opts in with ``metadata.references`` (comma-separated reference names)
in its SKILL.md frontmatter; a domain skill names its pack with
``metadata.domain``.
"""
from __future__ import annotations

from typing import Any, Callable, Dict, List

from jinja2 import Environment, PackageLoader, StrictUndefined

from ontogate.config import OntologyRegistry
from ontogate.models import TrustTier

GENERATED_HEADER = "<!-- Generated by `ontogate skills build` from the ontology bundle. Do not edit. -->\n"

_env = Environment(
    loader=PackageLoader("ontogate", "templates/skills"),
    undefined=StrictUndefined,
    trim_blocks=True,
    lstrip_blocks=True,
    keep_trailing_newline=True,
)


def _name(reg: OntologyRegistry, uri: str) -> str:
    concept = reg.concepts.get(uri)
    return concept.name if concept else uri


def _department(reg: OntologyRegistry, ref: str) -> str:
    dept = reg.departments.get(ref)
    return dept.label if dept else ref


def _differentiators(reg: OntologyRegistry, uris: List[str]) -> List[str]:
    """What tells the candidates of an ambiguous designation apart (no numbers)."""
    concepts = [reg.concepts[u] for u in uris if u in reg.concepts]
    out: List[str] = []
    unit_sets = [set(c.units) for c in concepts]
    if len(unit_sets) > 1 and not set.intersection(*unit_sets):
        out.append("reported unit (" + "; ".join(f"{c.name}: {', '.join(c.units)}" for c in concepts) + ")")
    facet_ids = sorted({f for c in concepts for f in c.facets})
    for fid in facet_ids:
        values = [c.facets.get(fid) for c in concepts]
        if len(set(values)) > 1:
            facet = reg.facets.get(fid)
            label = facet.label if facet and facet.label else fid
            out.append(f"{label} ({', '.join(f'{c.name}: {c.facets.get(fid, chr(8212))}' for c in concepts)})")
    if not out:
        # Nothing structural differs: name the unambiguous designations of each candidate.
        for c in concepts:
            own = sorted(d.text for d in reg.designations.values() if d.denotes == [c.uri])
            out.append(f"{c.name}: say " + (" or ".join(f"`{t}`" for t in own) if own else "the full name"))
    return out


def designation_index(reg: OntologyRegistry) -> Dict[str, Any]:
    rows = []
    for text, d in sorted(reg.designations.items()):
        if not d.is_ambiguous:
            continue
        rows.append({
            "text": d.text,
            "candidates": [f"{_name(reg, u)} (`{u}`)" for u in d.denotes],
            "differentiators": _differentiators(reg, d.denotes),
        })
    return {"rows": rows}


def facet_questions(reg: OntologyRegistry) -> Dict[str, Any]:
    def rows(facets):
        return [{
            "id": f.id,
            "label": f.label or f.id,
            "question": f.question or f"Which {f.label or f.id} applies?",
            "allowed": list(f.values),
            "synonyms": sorted(f.value_synonyms.items()),
        } for f in sorted(facets.values(), key=lambda f: f.id)]
    return {"facets": rows(reg.facets), "population": rows(reg.population_facets)}


def trust_caveats(reg: OntologyRegistry) -> Dict[str, Any]:
    caveats = dict(reg.trust_policy.get("caveats") or {})
    missing = [t.value for t in TrustTier if t.value not in caveats]
    if missing:
        raise ValueError(f"core trust_policy.caveats has no wording for tier(s): {', '.join(missing)}")
    return {
        "tiers": [{"tier": t.value, "wording": caveats[t.value]} for t in TrustTier],
        "stale": caveats.get("stale"),
        "clinically_unvalidated": caveats.get("clinically_unvalidated"),
    }


def panels(reg: OntologyRegistry) -> Dict[str, Any]:
    out = []
    for pid, panel in sorted(reg.panels.items()):
        specimen = reg.specimens.get(panel.specimen_id or panel.specimen)
        out.append({
            "id": pid,
            "name": panel.name,
            "specimen": specimen.label if specimen else panel.specimen,
            "collection_method": panel.collection_method,
            "designations": list(panel.designations),
            "steps": [{
                "tube": step.tube,
                "department": _department(reg, step.department_id or step.department),
                "description": step.description or "",
                "includes": [_name(reg, u) for u in step.includes],
            } for step in sorted(panel.tube_rules, key=lambda s: s.tube)],
        })
    return {"panels": out}


def domain_summary(reg: OntologyRegistry) -> Dict[str, Any]:
    domains = [{"id": d.get("id"), "label": d.get("label", d.get("id")),
                "description": " ".join(str(d.get("description", "")).split()),
                "disclaimer": " ".join(str(d.get("disclaimer", "")).split())}
               for _, d in sorted(reg.domains.items())]
    observables = [{
        "uri": c.uri,
        "name": c.name,
        "department": c.department,
        "units": ", ".join(c.units) or "none",
        "trust_tier": c.trust_tier.value,
        "status": c.status,
    } for c in sorted(reg.concepts.values(), key=lambda c: c.uri)]
    return {"domains": domains, "observables": observables,
            "panels": [p.name for _, p in sorted(reg.panels.items())]}


RENDERERS: Dict[str, Callable[[OntologyRegistry], Dict[str, Any]]] = {
    "designation-index": designation_index,
    "facet-questions": facet_questions,
    "trust-caveats": trust_caveats,
    "panels": panels,
    "domain-summary": domain_summary,
}


def render_reference(name: str, reg: OntologyRegistry) -> str:
    """Render one named reference (``<name>.md``) from the registry."""
    if name not in RENDERERS:
        raise KeyError(f"Unknown skill reference '{name}'. Known: {', '.join(sorted(RENDERERS))}")
    body = _env.get_template(f"{name}.md.j2").render(**RENDERERS[name](reg))
    return GENERATED_HEADER + body
